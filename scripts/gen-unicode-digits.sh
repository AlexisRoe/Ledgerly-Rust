#!/usr/bin/env bash
# Generates crates/shared/src/money/unicode_digits.rs from the Unicode Character Database that OpenJDK 25 uses.
#
# Ledgerly-Java parses amounts with `new BigDecimal(String)`, which takes every character for which
# `Character.isDigit(char)` is true: the decimal digits (general category Nd) of Unicode 16.0, the version
# `java.lang.Character` of JDK 25 is based on. A `char` is one UTF-16 unit, so only digits of the Basic
# Multilingual Plane count; a supplementary digit arrives as two surrogates, and those are not digits.
# Run it with `just gen-unicode-digits`; the result is committed and must not be edited by hand.
#
# Usage: scripts/gen-unicode-digits.sh [path/to/UnicodeData.txt]
#   Without an argument the file is downloaded. With one, that local copy is used (it must have the pinned checksum).
set -euo pipefail

cd "$(dirname "$0")/.."

version="16.0.0"
url="https://www.unicode.org/Public/${version}/ucd/UnicodeData.txt"
expected_sha256="ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f"
out="crates/shared/src/money/unicode_digits.rs"

workdir="$(mktemp -d)"
trap 'rm -rf "$workdir"' EXIT

if [[ $# -ge 1 ]]; then
    cp "$1" "$workdir/UnicodeData.txt"
else
    curl --fail --silent --show-error --location --max-time 60 -o "$workdir/UnicodeData.txt" "$url"
fi

if command -v shasum >/dev/null 2>&1; then
    actual_sha256="$(shasum -a 256 "$workdir/UnicodeData.txt" | cut -d' ' -f1)"
else
    actual_sha256="$(sha256sum "$workdir/UnicodeData.txt" | cut -d' ' -f1)"
fi
if [[ "$actual_sha256" != "$expected_sha256" ]]; then
    echo "gen-unicode-digits: checksum of UnicodeData.txt is $actual_sha256, expected $expected_sha256" >&2
    exit 1
fi

# Fields: 0 code point, 2 general category, 6 decimal digit value. Every Nd character of the BMP is listed
# singly (no ranges), and Unicode guarantees that they come in runs of ten from 0 to 9; the script checks it.
zeros="$(awk -F';' '
    function fail(message) { print "gen-unicode-digits: " message > "/dev/stderr"; failed = 1; exit 1 }
    # POSIX awk has no strtonum.
    function hex(text,    value, i) {
        value = 0
        for (i = 1; i <= length(text); i++) value = value * 16 + index("0123456789ABCDEF", substr(text, i, 1)) - 1
        return value
    }
    $3 == "Nd" && length($1) == 4 {
        cp = hex($1)
        if ($7 == "0") { zero = cp; printf "0x%04X\n", cp }
        else if (cp != zero + $7) fail("U+" $1 " is digit " $7 " but not in the run starting at its zero")
        count++
    }
    END { if (!failed && count % 10 != 0) fail("found " count " BMP digits, not a multiple of ten") }
' "$workdir/UnicodeData.txt")"

count="$(echo "$zeros" | wc -l | tr -d ' ')"
{
    echo "// @generated by scripts/gen-unicode-digits.sh. Do not edit: run \`just gen-unicode-digits\`."
    echo "//"
    echo "// Source: ${url}"
    echo "// Unicode ${version} (the version of java.lang.Character in OpenJDK 25), sha256 ${expected_sha256}"
    echo
    echo "/// The digit zero of every run of decimal digits (general category Nd) in the Basic Multilingual Plane,"
    echo "/// ascending. The run from each zero holds the digits 0 to 9 in order. These are the \`char\`s for which Java's"
    echo "/// \`Character.isDigit\` is true."
    echo "pub(super) const ZEROS: [u16; ${count}] = ["
    echo "$zeros" | sed 's/.*/    &,/'
    echo "];"
} > "$out"
echo "gen-unicode-digits: wrote $out ($count runs of ten)"
