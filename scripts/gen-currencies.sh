#!/usr/bin/env bash
# Generates crates/shared/src/money/currencies.rs from OpenJDK's ISO 4217 data (plan M0.4).
#
# Ledgerly-Java validates currencies with java.util.Currency, so the set of accepted codes and their fraction
# digits is whatever the JDK it runs on ships. This script turns that data file, at a pinned tag and checksum,
# into a Rust table. Run it with `just gen-currencies`; the result is committed and must not be edited by hand.
#
# Usage: scripts/gen-currencies.sh [path/to/CurrencyData.properties]
#   Without an argument the file is downloaded. With one, that local copy is used (it must have the pinned checksum).
set -euo pipefail

cd "$(dirname "$0")/.."

tag="jdk-25-ga"
url="https://raw.githubusercontent.com/openjdk/jdk/${tag}/src/java.base/share/data/currency/CurrencyData.properties"
expected_sha256="7d0f7a56d252d21c50a24a7b8c03a74616f622a85359cf427e560ddaa70a7fc0"
out="crates/shared/src/money/currencies.rs"

workdir="$(mktemp -d)"
trap 'rm -rf "$workdir"' EXIT

if [[ $# -ge 1 ]]; then
    cp "$1" "$workdir/CurrencyData.properties"
else
    curl --fail --silent --show-error --location --max-time 60 -o "$workdir/CurrencyData.properties" "$url"
fi

if command -v shasum >/dev/null 2>&1; then
    actual_sha256="$(shasum -a 256 "$workdir/CurrencyData.properties" | cut -d' ' -f1)"
else
    actual_sha256="$(sha256sum "$workdir/CurrencyData.properties" | cut -d' ' -f1)"
fi
if [[ "$actual_sha256" != "$expected_sha256" ]]; then
    echo "gen-currencies: checksum of CurrencyData.properties is $actual_sha256, expected $expected_sha256" >&2
    exit 1
fi

# The file is a Java properties file. Only these keys matter here:
#   all=ADP020-AED784-...     every currency code java.util.Currency knows, each followed by its numeric code
#   minor0=..., minor3=...    codes whose default fraction digits are not 2
#   minorUndefined=...        codes without minor units: getDefaultFractionDigits() returns -1
#   dataVersion=179           the ISO 4217 amendment the data follows
# Prints "dataVersion <n>" and one "<code> <digits>" line per currency, digits being -1 for "undefined".
awk '
    function fail(message) {
        print "gen-currencies: " message > "/dev/stderr"
        failed = 1
        exit 1
    }
    { sub(/\r$/, "") }
    /^[ \t]*#/ { next }
    {
        line = pending $0
        if (line ~ /\\$/) {
            sub(/\\$/, "", line)
            pending = line
            next
        }
        pending = ""
        gsub(/[ \t]/, "", line)
        eq = index(line, "=")
        if (eq == 0) {
            next
        }
        key = substr(line, 1, eq - 1)
        value = substr(line, eq + 1)
        if (key == "dataVersion") {
            data_version = value
        } else if (key == "all") {
            n = split(value, parts, "-")
            for (i = 1; i <= n; i++) {
                if (parts[i] !~ /^[A-Z][A-Z][A-Z][0-9][0-9][0-9]$/) {
                    fail("unexpected entry in all=: " parts[i])
                }
                digits[substr(parts[i], 1, 3)] = 2
            }
        } else if (key ~ /^minor[0-9]$/ || key == "minorUndefined") {
            n = split(value, parts, "-")
            for (i = 1; i <= n; i++) {
                special[parts[i]] = (key == "minorUndefined") ? -1 : substr(key, 6)
            }
        }
    }
    END {
        if (failed) {
            exit 1
        }
        if (data_version == "") {
            fail("dataVersion not found")
        }
        for (code in special) {
            if (!(code in digits)) {
                fail("minor-unit entry for a code missing from all=: " code)
            }
            digits[code] = special[code]
        }
        print "dataVersion " data_version
        for (code in digits) {
            print code " " digits[code]
        }
    }
' "$workdir/CurrencyData.properties" >"$workdir/parsed"

data_version="$(sed -n 's/^dataVersion //p' "$workdir/parsed")"
count="$(grep -c -v '^dataVersion ' "$workdir/parsed")"

{
    cat <<HEADER
// @generated by scripts/gen-currencies.sh. Do not edit: run \`just gen-currencies\`.
//
// Source: ${url}
// Tag: ${tag} (ISO 4217 dataVersion ${data_version}), sha256 ${expected_sha256}

/// Every currency code \`java.util.Currency.getInstance\` accepts in OpenJDK 25, sorted by code, each with what
/// \`getDefaultFractionDigits()\` returns for it. \`None\` stands for Java's \`-1\`: a code without minor units
/// (gold, test codes, "no currency"), which \`Money\` rejects.
///
/// Withdrawn codes (DEM, ITL, ...) are included, because Java still accepts them.
pub(super) const CURRENCIES: [(&str, Option<u8>); ${count}] = [
HEADER
    grep -v '^dataVersion ' "$workdir/parsed" | LC_ALL=C sort | while read -r code digits; do
        if [[ "$digits" == "-1" ]]; then
            printf '    ("%s", None),\n' "$code"
        else
            printf '    ("%s", Some(%s)),\n' "$code" "$digits"
        fi
    done
    echo "];"
} >"$out"

echo "gen-currencies: wrote ${count} currencies (dataVersion ${data_version}) to ${out}"
